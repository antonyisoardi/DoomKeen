export const HERO_TORSO = TORSO;

// Returns { "stand_walkA": rows, ... } for every torso x legs combination, plus "dead".
export function heroFrames() {
  const frames = {};
  Object.entries(TORSO).forEach(([torsoName, torso]) => {
    Object.entries(LEGS).forEach(([legName, legs]) => {
      frames[`${torsoName}_${legName}`] = [...HEAD, ...torso, ...legs];
    });
  });
  frames.dead = [...frames.stand_stand].reverse();
  return frames;
}
