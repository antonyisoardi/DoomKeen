export function itemFrames() {
  const frames = Object.fromEntries(Object.entries(RAW).map(([k, rows]) => [k, padTo(rows, 16, 16)]));
  frames.keyRed = padTo(remap(KEYCARD, { X: 'C' }), 16, 16, 3);
  frames.keyBlue = padTo(remap(KEYCARD, { X: '9' }), 16, 16, 3);
  frames.keyYellow = padTo(remap(KEYCARD, { X: 'E' }), 16, 16, 3);
  return frames;
}
