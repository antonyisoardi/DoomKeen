export const GLYPH_BITS = Object.freeze(
  Object.fromEntries(Object.entries(GLYPHS).map(([ch, rows]) => [ch, rows.split(',')])),
);

const cache = new Map();

function glyphCanvas(ch, color) {
  const key = `${ch}|${color}`;
  const hit = cache.get(key);
  if (hit) return hit;
  const bits = GLYPH_BITS[ch] || GLYPH_BITS['?'];
  const canvas = document.createElement('canvas');
  canvas.width = 5;
  canvas.height = 7;
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = egaColor(color);
  bits.forEach((row, y) => {
    for (let x = 0; x < 5; x++) if (row[x] === '1') ctx.fillRect(x, y, 1, 1);
  });
  cache.set(key, canvas);
  return canvas;
}

export function textWidth(text, scale = 1) {
  return String(text).length * GLYPH_W * scale;
}

export function drawText(ctx, text, x, y, color = 15, { scale = 1, shadow = null } = {}) {
  const str = String(text).toUpperCase();
  if (shadow !== null) drawText(ctx, str, x + scale, y + scale, shadow, { scale });
  for (let i = 0; i < str.length; i++) {
    const glyph = glyphCanvas(str[i], color);
    ctx.drawImage(glyph, Math.round(x + i * GLYPH_W * scale), Math.round(y), 5 * scale, 7 * scale);
  }
}

export function drawTextCentered(ctx, text, centerX, y, color = 15, opts = {}) {
  const w = textWidth(text, opts.scale || 1);
  drawText(ctx, text, Math.round(centerX - w / 2), y, color, opts);
}
